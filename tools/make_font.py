"""Render DejaVu Sans (free licence, Bitstream Vera derivative) into anti-aliased
glyph cells for the crew console, which has no font library on the target.

Writes include/elv_font.h: for each size, one alpha cell per printable ASCII
character (32 to 126), as wide as the character's advance and as tall as the
line. The console blends these cells into its QNX Screen buffer.

Usage: python -I tools/make_font.py DejaVuSans.ttf DejaVuSans-Bold.ttf
"""
import sys
from PIL import Image, ImageDraw, ImageFont

SIZES = [("SMALL", 0, 17, "all"), ("BODY", 1, 24, "all"), ("LARGE", 1, 40, "all"), ("HUGE", 1, 104, "0123456789.:% -/")]


def main():
    reg, bold = sys.argv[1], sys.argv[2]
    out = ["/* Generated by tools/make_font.py from DejaVu Sans (free licence). Do not edit. */",
           "#ifndef ELV_FONT_H", "#define ELV_FONT_H", "#include <stdint.h>",
           "typedef struct { uint8_t w; uint32_t off; } elv_glyph_t;",
           "typedef struct { int h; const elv_glyph_t *g; const uint8_t *a; } elv_font_t;"]
    for name, is_bold, px, chars in SIZES:
        font = ImageFont.truetype(bold if is_bold else reg, px)
        asc, desc = font.getmetrics()
        h = asc + desc
        data, glyphs = bytearray(), []
        for c in range(32, 127):
            ch = chr(c)
            if chars != "all" and ch not in chars:
                glyphs.append((0, 0)); continue
            w = max(1, int(round(font.getlength(ch))))
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=255)
            glyphs.append((w, len(data)))
            data += img.tobytes()
        out.append("static const elv_glyph_t ELV_G_%s[95] = { %s };" % (name, ", ".join("{%d,%d}" % g for g in glyphs)))
        rows = [", ".join(str(b) for b in data[i:i + 64]) for i in range(0, len(data), 64)]
        out.append("static const uint8_t ELV_A_%s[%d] = {\n%s };" % (name, len(data), ",\n".join(rows)))
        out.append("static const elv_font_t ELV_FONT_%s = { %d, ELV_G_%s, ELV_A_%s };" % (name, h, name, name))
    out.append("#endif")
    open("include/elv_font.h", "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
